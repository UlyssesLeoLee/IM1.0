def render_template(t: dict) -> str:
    """把一份模板元数据渲染成完整的 Markdown 文档。"""
    raw = f"""
---
doc_id: {t['no']}
title_ja: {t['title_ja']}
title_zh: {t['title_zh']}
phase: {t['phase_dir']}
activity_no: {t['no']}
owners: {t['owners']}
status: Draft
version: 1.0.0
---

# {t['no']}. {t['title_ja']} / {t['title_zh']}

> 项目: **{PROJECT_NAME}** — {PROJECT_DESC}
> 工程: No.{t['no']} ({t['phase_label']})
> 责任方: {t['owners']}

## 1. 目的 (Purpose)

{t['purpose']}

## 2. 适用范围 (Scope)

{t['scope']}

## 3. 责任方 (Owners)

{t['owners']}

## 4. 前置依赖 (Prerequisites / Inputs)

{chr(10).join('- ' + x for x in t['inputs']) if t['inputs'] else '- (无)'}

## 5. 输出 / 模板正文 (Body)

{t['body']}

## 6. 验收标准 (Acceptance Criteria)

{t['acceptance']}

## 7. 关联文档 (References)

- 上游: {', '.join(t['refs_up'])}
- 下游: {', '.join(t['refs_down'])}
- 略称: {t['abbrev']}

## 8. 变更记录 (Change Log)

| 版本 | 日期 | 修订人 | 内容 |
|---|---|---|---|
| 1.0.0 | YYYY-MM-DD | (待定) | 初版 |
"""
    return dedent(raw).lstrip("\n")


def make(no: str, filename: str, title_ja: str, title_zh: str,
         owners: str, purpose: str, scope: str, inputs: list[str],
         body: str, acceptance: str,
         refs_up: list[str], refs_down: list[str], abbrev: str,
         phase_dir: str, phase_label: str) -> dict:
    return {
        "no": no,
        "filename": filename,
        "title_ja": title_ja,
        "title_zh": title_zh,
        "owners": owners,
        "purpose": purpose,
        "scope": scope,
        "inputs": inputs,
        "body": body,
        "acceptance": acceptance,
        "refs_up": refs_up,
        "refs_down": refs_down,
        "abbrev": abbrev,
        "phase_dir": phase_dir,
        "phase_label": phase_label,
    }


