# ---------------------------------------------------------------------------
# Phase README 生成
# ---------------------------------------------------------------------------

def render_phase_readme(phase_dir: str, phase_label: str, no_range: str, desc: str, gate: str,
                       items: list[dict]) -> str:
    lines = []
    lines.append(f"# {phase_label}\n")
    lines.append(f"> 工程范围: No.{no_range}\n")
    lines.append(f"> 阶段目的: {desc}\n")
    lines.append(f"> 出口 GATE: **{gate}**\n\n")
    lines.append("## 文档清单\n")
    lines.append("| 工程 | 文档 | 略称 | 责任方 | 文件 |\n")
    lines.append("|---|---|---|---|---|\n")
    for t in items:
        title = f"{t['title_ja']} / {t['title_zh']}"
        abbrev = t['abbrev'] if t['abbrev'] != '—' else '—'
        lines.append(f"| {t['no']} | {title} | {abbrev} | {t['owners']} | [{t['filename']}]({t['filename']}) |\n")
    lines.append("\n## 使用建议\n")
    lines.append(f"1. 进入本 Phase 前,确认上游 GATE({gate} 的上游)已通过。\n")
    lines.append(f"2. 按 No. 顺序逐项填写对应文档;不必强求一次写满,可迭代。\n")
    lines.append(f"3. 完成本 Phase 全部文档后,申请 {gate} 评审;通过后才能进入下一 Phase。\n")
    lines.append(f"4. 残留问题 / 范围变更走 `docs/templates/15-management/136-scope-change-record.md`。\n")
    return "".join(lines)


# ---------------------------------------------------------------------------
# 总索引生成
# ---------------------------------------------------------------------------

def render_index(items: list[dict]) -> str:
    out = []
    out.append("# IM1.0 Workflow Templates\n\n")
    out.append("> 本目录是 `docs/Workflow.md` 中 150 个工程活动的配套文档模板。\n")
    out.append("> 每个 .md 文件 = 1 个工程活动的主输出文档模板;按 16 个 Phase 子目录组织。\n\n")
    out.append("## 目录\n\n")
    for phase_dir, phase_label, no_range, desc, gate in PHASES:
        out.append(f"- [{phase_label} ({no_range})](./{phase_dir}/) — {desc};GATE: **{gate}**\n")
    out.append("\n## 全部模板(按工程编号)\n\n")
    out.append("| No | 阶段 | 文档(中文) | 略称 | 文件 |\n")
    out.append("|---|---|---|---|---|\n")
    for t in items:
        phase_dir = t['phase_dir']
        out.append(f"| {t['no']} | {phase_dir} | {t['title_zh']} | {t['abbrev']} | [{t['filename']}](./{phase_dir}/{t['filename']}) |\n")
    out.append("\n## 维护\n\n")
    out.append("- 模板生成脚本:`scripts/gen_workflow_templates.py`\n")
    out.append("- 重新生成:删除本目录后,运行 `python scripts\\gen_workflow_templates.py`\n")
    out.append("- 模板版本随项目演进;变更请更新生成脚本。\n")
    return "".join(out)


# ---------------------------------------------------------------------------
# 主程序
# ---------------------------------------------------------------------------

def main() -> int:
    print(f"[gen] 模板总数: {len(ALL_TEMPLATES)}")
    print(f"[gen] 目标目录: {ROOT}")

    ROOT.mkdir(parents=True, exist_ok=True)

    # 1. 按 Phase 写入每个工程活动的模板
    for t in ALL_TEMPLATES:
        d = ROOT / t['phase_dir']
        d.mkdir(parents=True, exist_ok=True)
        f = d / t['filename']
        f.write_text(render_template(t), encoding="utf-8")

    # 2. 为每个 Phase 生成 README(子目录索引)
    for phase_dir, phase_label, no_range, desc, gate in PHASES:
        items = [t for t in ALL_TEMPLATES if t['phase_dir'] == phase_dir]
        d = ROOT / phase_dir
        d.mkdir(parents=True, exist_ok=True)
        (d / "README.md").write_text(
            render_phase_readme(phase_dir, phase_label, no_range, desc, gate, items),
            encoding="utf-8"
        )

    # 3. 生成总索引
    (ROOT / "README.md").write_text(render_index(ALL_TEMPLATES), encoding="utf-8")

    # 4. 校验
    written = sorted(ROOT.rglob("*.md"))
    print(f"[gen] 写入文件数: {len(written)}")
    expected_dirs = {p[0] for p in PHASES}
    actual_dirs = {p.parent.name for p in written if p.name != "README.md"}
    missing_dirs = expected_dirs - actual_dirs
    if missing_dirs:
        print(f"[err] 缺失 Phase 目录: {missing_dirs}")
        return 1
    print("[ok] 全部 16 个 Phase 目录齐备,模板已生成")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())



